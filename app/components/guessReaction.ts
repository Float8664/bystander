/**
 * Фраза-реакция на промах между догадкой пользователя и расчётом.
 * Это ФОРМАТИРОВАНИЕ ТЕКСТА, не модель: сюда не переезжает никакая математика
 * вероятностей — только пороги, по которым выбирается формулировка.
 * Тон: без морали и без жаргона, разговорно.
 *
 * guess и actual — в процентах (0–100).
 */
export function getGuessReaction(guess: number, actual: number): string {
  const diff = guess - actual

  if (diff > 30) {
    return "Ты сильно переоценил соседей. Разрыв больше, чем кажется на глаз, — в этом и суть эффекта свидетеля."
  }
  if (diff > 10) {
    return "Ты ждал большего от соседей, чем даёт расчёт. Обычная интуиция — и обычно она завышает."
  }
  if (diff >= -10) {
    return "Ты угадал довольно близко. Похоже, ты уже чувствуешь, как это работает."
  }
  if (diff >= -30) {
    return "Ты был осторожнее расчёта — здесь шанс выше, чем ты предположил."
  }
  return "Ты сильно недооценил: расчёт даёт заметно больше, чем ты ожидал."
}

/**
 * Короткая метка промаха — для подписи рядом с цифрами.
 */
export function getGuessDelta(guess: number, actual: number): string {
  const diff = Math.round((guess - actual) * 10) / 10
  if (Math.abs(diff) < 0.05) return "точь-в-точь"
  return diff > 0 ? `выше на ${Math.abs(diff)} п.п.` : `ниже на ${Math.abs(diff)} п.п.`
}
